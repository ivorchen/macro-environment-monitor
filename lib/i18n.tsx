export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, "zh-CN": zhCN, "zh-TW": zhTW };

export function normalizeLocale(value: string | null | undefined): Locale {
  const normalized = value?.toLowerCase().replace("_", "-") ?? "";
  if (/^zh-(tw|hk|mo|hant)/.test(normalized)) return "zh-TW";
  if (/^zh/.test(normalized)) return "zh-CN";
  return "en";
}

export function translate(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}) {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    MESSAGES[locale][key] ?? MESSAGES.en[key],
  );
}

type I18nContextValue = {
  locale: Locale;
  intlLocale: string;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, values?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    const detected = normalizeLocale(stored ?? window.navigator.language);
    const timer = window.setTimeout(() => setLocaleState(detected), 0);
    return () => window.clearTimeout(timer);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = (nextLocale: Locale) => {
    setLocaleState(nextLocale);
    window.localStorage.setItem(LOCALE_STORAGE_KEY, nextLocale);
    document.documentElement.lang = nextLocale;
  };
  const value = useMemo<I18nContextValue>(() => ({
    locale,
    intlLocale: locale === "en" ? "en-US" : locale,
    setLocale,
    t: (key, values) => translate(locale, key, values),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used within I18nProvider.");
  return value;
}
